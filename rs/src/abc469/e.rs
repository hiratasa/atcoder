fn main() {
    input! {
        n: usize, k: usize,
        s: Chars,
    };

    let sums = once(0)
        .chain(s.iter().copied().map(|x| x == 'o').map_into::<usize>())
        .cumsum::<usize>()
        .collect::<Vec<_>>();

    let ans = lower_bound(0.0f64, 1.0f64, 1e-8, |w| {
        let ok = (0..=n)
            .scan((f64::MAX, 0), |(m, j), i| {
                while *j < i && sums[i] - sums[*j] >= k {
                    *m = m.min(sums[*j] as f64 - (*j as f64) * w);
                    *j += 1;
                }
                Some(sums[i] as f64 - (i as f64) * w >= *m)
            })
            .any(|ok| ok);

        if ok {
            Ordering::Less
        } else {
            Ordering::Greater
        }
    });

    println!("{ans}");
}

