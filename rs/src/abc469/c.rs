fn main() {
    input! {
        n: usize,
        s: Chars,
    };

    let t = once(0)
        .chain(s.iter().copied().map(|x| (x == 'o') as usize))
        .cumsum::<usize>()
        .collect::<Vec<_>>();

    for i in 0..n {
        let ans = lower_bound_int(i, n, |j| (j - i).cmp(&t[j]).then(Ordering::Less));

        println!("{ans}");
    }
}

