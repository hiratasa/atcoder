fn main() {
    input! {
        n: usize, k: usize,
        a: [usize; n],
    };

    let ans = lower_bound_int(1, 1usize << 61, |m| {
        a.iter()
            .copied()
            .enumerate()
            .map(|(i, x)| (m.saturating_sub(x) + i) / (1 + i))
            .try_fold(0usize, |s, x| s.checked_add(x))
            .unwrap_or(usize::MAX)
            .cmp(&k)
            .then(Ordering::Less)
    }) - 1;

    println!("{ans}");
}

