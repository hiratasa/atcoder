fn main() {
    input! {
        n: usize, k: usize,
        mut lr: [(usize, usize); n],
    };

    lr.sort_by_key(|&(l, r)| (r, Reverse(l)));

    let ans = lower_bound_int(1, 1usize << 30, |d| {
        lr.iter()
            .copied()
            .scan(0, |last, (l, r)| {
                if *last <= l {
                    *last = r + d;
                    Some(1)
                } else {
                    Some(0)
                }
            })
            .sum::<usize>()
            .cmp(&k)
            .reverse()
            .then(Ordering::Less)
    }) - 1;

    if ans == 0 {
        println!("-1");
    } else {
        println!("{ans}");
    }
}

