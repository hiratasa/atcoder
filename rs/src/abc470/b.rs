fn main() {
    input! {
        n: usize,
        c: [usize; n],
    };

    let freq = c.into_iter().fold(vec![0; n + 1], |mut freq, x| {
        freq[x] += 1;
        freq
    });

    let ans = freq.into_iter().map(|m| n - m).min().unwrap();

    println!("{ans}");
}

